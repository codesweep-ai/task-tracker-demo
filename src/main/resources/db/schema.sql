-- task-tracker schema (PostgreSQL)
-- Loaded by the Postgres container at init time (docker-entrypoint-initdb.d);
-- the app never creates its own schema.

DROP TABLE IF EXISTS task;
DROP TABLE IF EXISTS project;
DROP TABLE IF EXISTS person;

CREATE TABLE person (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username  VARCHAR(64)  NOT NULL UNIQUE,
  full_name VARCHAR(128) NOT NULL,
  password  VARCHAR(128) NOT NULL,
  role      VARCHAR(16)  NOT NULL
            CHECK (role IN ('ADMIN','MANAGER','MEMBER','VIEWER'))
);

CREATE TABLE project (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(128)  NOT NULL,
  description VARCHAR(1024),
  state       VARCHAR(16)   NOT NULL DEFAULT 'ACTIVE'
              CHECK (state IN ('ACTIVE','ARCHIVED')),
  owner_id    BIGINT        NOT NULL,
  CONSTRAINT fk_project_owner FOREIGN KEY (owner_id) REFERENCES person(id)
);

CREATE TABLE task (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       VARCHAR(256)  NOT NULL,
  description VARCHAR(4000),
  status      VARCHAR(20)   NOT NULL DEFAULT 'OPEN'
              CHECK (status IN ('OPEN','IN_PROGRESS','PENDING_APPROVAL','DONE')),
  priority    VARCHAR(16)   NOT NULL DEFAULT 'MEDIUM'
              CHECK (priority IN ('LOW','MEDIUM','HIGH')),
  assignee_id BIGINT,
  project_id  BIGINT        NOT NULL,
  due_date    DATE,
  updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- refreshed on every mutation
  CONSTRAINT fk_task_project  FOREIGN KEY (project_id)  REFERENCES project(id),
  CONSTRAINT fk_task_assignee FOREIGN KEY (assignee_id) REFERENCES person(id)
);
